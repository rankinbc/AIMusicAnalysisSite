import { expect, test } from '@playwright/test';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

// Story 12.7 (AC2) — the first-run smoke: one headless pass that catches
// verify-gate, dead-handoff, and dead-UI regressions together.
//
//   anon → / → /login (redirect via the _app guard)
//   register a fresh account → /library (empty first-run state)
//   + New song → NewSongDialog → UnifiedUploadDialog (mix only)
//   Upload & analyze → /songs/$songId/results/$jobId
//   wait for the report (ReportView), assert the job never fails
//   Open in Listen → /listen-rack/$versionId mounts
//
// Pre-reqs (the Playwright webServer only starts Vite — the rest must be up):
//   * docker compose -f docker/docker-compose.yml up -d postgres redis
//   * dotnet ef database update (migrations applied)
//   * BFF: ASPNETCORE_ENVIRONMENT=Development dotnet run (:5000) —
//     Development is REQUIRED: Auth:DevAutoVerify=true auto-verifies the
//     fresh account so the dispatch is not blocked by the verify gate.
//   * worker: python -m dramatiq app.dramatiq_app --processes 1 --threads 1
//     --queues coach analysis-paid analysis-free maintenance
//     from an interpreter with audio_analysis installed and LLM_FAKE=1
//     (components/worker/.env) — zero Anthropic spend, deterministic verdicts.
//   * MinIO NOT required: the presigned probe 501s and the mix upload takes
//     the legacy proxy fallback path (which this smoke then exercises).
//   * No allin1 docker image needed: structure detection degrades
//     gracefully and the job still completes (the fast path).
//   * test-tone.wav is generated by playwright/global-setup.ts if missing.
//
// HEADLESS ONLY — never pass --headed/--ui on shared/dev machines.

test.describe.configure({ mode: 'serial' });

test('first-run: register → upload → report → listen', async ({ page }) => {
  test.setTimeout(360_000); // cold worker + first-run model warmup budget

  // Diagnostics: API traffic + page errors land in the test output so a
  // failure at any step shows WHAT the app was doing (worker down, 4xx code,
  // console crash) without re-running under a tracer.
  page.on('request', (r) => {
    if (r.url().includes('/api/')) console.log(`>> ${r.method()} ${r.url()}`);
  });
  page.on('response', (r) => {
    if (r.url().includes('/api/')) console.log(`<< ${r.status()} ${r.url()}`);
  });
  page.on('pageerror', (e) => console.log(`PAGE ERROR: ${e.message}`));

  // 1. Anon visit bounces to login.
  await page.goto('/');
  await expect(page).toHaveURL(/\/login(\?.*)?$/);

  // 2. Register a fresh account (DevAutoVerify stamps it verified).
  await page.getByRole('link', { name: /Create one/i }).click();
  await expect(page).toHaveURL(/\/register$/);
  const email = `smoke+${Date.now()}@spectr.test`;
  const emailBox = page.getByLabel('Email');
  const passwordBox = page.getByLabel('Password');
  // Cold Vite dev keeps streaming route modules after first paint; a late
  // module swap can REMOUNT the form and wipe a fill (controlled useState
  // resets), so the click submits empty fields and HTML5 `required` silently
  // blocks it. Settle the module graph, then fill→verify→submit→navigated as
  // ONE retried unit: the only observed failure mode is a blocked submit
  // (no POST fired), so a retry never double-registers.
  await page.waitForLoadState('networkidle');
  await expect(async () => {
    await emailBox.fill(email);
    await passwordBox.fill('correct-horse-battery-staple');
    await expect(emailBox).toHaveValue(email, { timeout: 500 });
    await page.getByRole('button', { name: /Create account/i }).click();
    // 3. Registration navigates to the library (full page nav).
    await expect(page).toHaveURL(/\/library$/, { timeout: 10_000 });
  }).toPass({ timeout: 60_000 });
  await expect(page.getByText('Your library starts here')).toBeVisible();

  // 4. Two-dialog flow: + New song → name → Create song → upload dialog.
  await page.getByRole('button', { name: /\+ New song/ }).first().click();
  await page.getByPlaceholder('Untitled song').fill(`Smoke ${Date.now()}`);
  await page.getByRole('button', { name: /^Create song$/ }).click();

  // 5. UnifiedUploadDialog (with songId → titled "New version"): attach the
  //    fixture to the MIX input specifically — the dialog holds several
  //    hidden file inputs (.als / reference / stems).
  await expect(page.getByRole('heading', { name: 'New version' })).toBeVisible();
  const fixture = path.resolve(
    path.dirname(fileURLToPath(import.meta.url)), 'fixtures', 'test-tone.wav');
  await page.getByTestId('mix-file-input').setInputFiles(fixture);
  const submit = page.getByRole('button', { name: /Upload & analyze/ });
  await expect(submit).toBeEnabled({ timeout: 15_000 }); // entitlements loaded
  await submit.click();

  // 6. Results page is reached immediately; the report appears when the
  //    worker completes. Fail FAST if the pipeline errors instead of
  //    burning the full timeout.
  await expect(page).toHaveURL(/\/songs\/.+\/results\/.+/, { timeout: 60_000 });
  const report = page.getByTestId('report-view');
  const failed = page.getByText('Analysis failed.');
  await expect(report.or(failed).first()).toBeVisible({ timeout: 300_000 });
  await expect(failed, 'analysis job failed — check worker logs').toBeHidden();
  await expect(report).toBeVisible();

  // 7. Listen reachability: the library card's Play button routes to the
  //    Listen rack for the latest version. (The report's own "Open in
  //    Listen" stays disabled until a fix is committed to the rack — the
  //    fix-carry-over handoff itself is story 12-4's integration test.)
  await page.goto('/library');
  await page.getByTitle('Play latest version').first().click();
  await expect(page).toHaveURL(/\/listen-rack\/[0-9a-f-]+/i, { timeout: 15_000 });
  await expect(page.getByTestId('listen-rack-page')).toBeVisible();
});
